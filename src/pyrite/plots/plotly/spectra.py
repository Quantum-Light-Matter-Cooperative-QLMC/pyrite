"""Plotly-first interactive source, comparison and case-basket spectra (#622).

Frames are generated by :mod:`pyrite.plots._spectrum_frames`, the same
numerical preparation used by the legacy Altair charts. Plotting never changes
spectral arrays, normalization (Phs/s/eV/uA) or checkpoint data. In particular,
wide bremsstrahlung tails and peak-aware sampling remain shared.
"""

from __future__ import annotations

import numpy as np
import plotly.graph_objects as go
from plotly.colors import qualitative

_COLORS = qualitative.Plotly

from ...results import records
from .._common import _case_title, _comparison_drop_message
from .._spectrum_frames import (
    _COMPARE_HUE_FIELDS,
    _compare_frame,
    _multi_case_frame,
    _narrow_line_domain,
    _tilt_records,
    _validate_band,
    _windowed_frame,
    spectrum_frame,
)

_INTENSITY_TITLE = "Intensity (Phs/s/eV/uA)"
_STYLES = {
    "total": ("solid", 2.2),
    "brem": ("dash", 1.3),
    "line": ("dot", 1.6),
    "coherent": ("dashdot", 2.2),
}


def _axis_type(kind: str) -> str:
    if kind not in {"linear", "log"}:
        raise ValueError(f"axis type must be 'linear' or 'log', got {kind!r}")
    return kind


def _axis_range(domain, kind):
    """Plotly's logarithmic axis range is in log10 units, unlike Altair's."""
    if domain is None:
        return None
    low, high = domain
    if kind == "log":
        if (low is not None and low <= 0) or (high is not None and high <= 0):
            raise ValueError("logarithmic axis domains must be positive")
        return [None if low is None else np.log10(low), None if high is None else np.log10(high)]
    return [low, high]


def _y_range(frame, *, y_type, x_domain=None, automatic_x_domain=True):
    view = _windowed_frame(frame, None if automatic_x_domain else x_domain)
    values = np.asarray(view["intensity"], dtype=float)
    positive = values[np.isfinite(values) & (values > 0)]
    if y_type == "log":
        if not positive.size:
            return None
        floor = max(float(positive.min()), float(positive.max()) * 1e-3)
        top = float(positive.max()) * 1.05
        return _axis_range((floor, max(top, floor * 1.05)), "log")
    if not automatic_x_domain and positive.size:
        return [0, float(positive.max()) * 1.05]
    return None


def _trace_series(df, *, hue, components, width, height, title, x_type, y_type, x_domain):
    """Build bounded Plotly traces without converting long frames to JSON records."""
    if df.empty:
        return None
    _axis_type(x_type)
    _axis_type(y_type)
    fig = go.Figure()
    labels = list(dict.fromkeys(df[hue].tolist()))
    # Numeric cases get stable, human-meaningful sorting, not lexical sorting.
    if all(isinstance(x, (int, float, np.integer, np.floating)) for x in labels):
        labels.sort()
    for idx, label in enumerate(labels):
        color = _COLORS[idx % len(_COLORS)]
        by_label = df[df[hue] == label]
        for component in components:
            part = by_label[by_label["component"] == component].sort_values("energy_eV")
            if part.empty:
                continue
            xs = part["energy_eV"].to_numpy(dtype=float)
            ys = part["intensity"].to_numpy(dtype=float)
            # Log axes cannot display nonpositive values; preserve original
            # input frames and mask only trace coordinates at presentation.
            plot_y = np.where(np.isfinite(ys) & (ys > 0), ys, np.nan) if y_type == "log" else ys
            dash, thickness = _STYLES[component]
            trace_type = go.Scattergl if xs.size > 6000 else go.Scatter
            fig.add_trace(
                trace_type(
                    x=xs,
                    y=plot_y,
                    mode="lines",
                    name=f"{label} · {component}" if len(components) > 1 else str(label),
                    legendgroup=str(idx),
                    line=dict(color=color, width=thickness, dash=dash),
                    customdata=np.full((xs.size, 1), str(label), dtype=object),
                    hovertemplate=(
                        f"{hue}: %{{customdata[0]}}<br>component: {component}"
                        "<br>Energy: %{x:.6g} eV<br>Intensity: %{y:.6g} Phs/s/eV/uA"
                        "<extra></extra>"
                    ),
                )
            )
    if not fig.data:
        return None
    fig.update_layout(
        title=title,
        width=width,
        height=height,
        hovermode="closest",
        legend=dict(title=_COMPARE_HUE_FIELDS.get(hue, "case")),
        xaxis=dict(title="Photon energy (eV)", type=x_type, range=_axis_range(x_domain, x_type)),
        yaxis=dict(
            title=_INTENSITY_TITLE,
            type=y_type,
            range=_y_range(
                df,
                y_type=y_type,
                x_domain=x_domain,
                automatic_x_domain=x_domain is None,
            ),
        ),
        margin=dict(l=70, r=24, b=62, t=70),
    )
    return fig


def spectrum_chart(
    results,
    settings,
    *,
    tilt_deg=None,
    include_brem=True,
    include_cxr=False,
    include_characteristic=True,
    include_channeling=True,
    include_coherent=False,
    collapse_azimuth=True,
    x_domain=None,
    x_type="linear",
    y_type="linear",
    band="narrow",
    max_points=5000,
    width=720,
    height=360,
):
    """Response-free spectra at one polar tilt; returns a Plotly figure or None."""
    _validate_band(band)
    recs = _tilt_records(results, tilt_deg)
    if not recs:
        return None
    frame = spectrum_frame(
        recs,
        settings,
        include_brem=include_brem,
        include_cxr=include_cxr,
        include_characteristic=include_characteristic,
        include_channeling=include_channeling,
        include_coherent=include_coherent,
        collapse_azimuth=collapse_azimuth,
        band=band,
        max_points=max_points,
    )
    return _trace_series(
        frame,
        hue="E0_keV",
        components=("total",)
        + (("brem",) if include_brem else ())
        + (("line",) if include_cxr else ())
        + (("coherent",) if include_coherent else ()),
        width=width,
        height=height,
        title=_case_title(recs[0]["case"], "response-free source", latex=False),
        x_type=x_type,
        y_type=y_type,
        x_domain=_narrow_line_domain(recs, band, x_domain),
    )


def compare_spectrum_chart(
    results,
    settings,
    *,
    hue,
    include_brem=True,
    include_cxr=False,
    include_characteristic=True,
    include_channeling=True,
    include_coherent=False,
    sum_components=False,
    x_domain=None,
    x_type="linear",
    y_type="linear",
    band="narrow",
    max_points=5000,
    width=720,
    height=360,
):
    """Plot one spectrum per selected case-field value (supports sum_components)."""
    _validate_band(band)
    if hue not in _COMPARE_HUE_FIELDS:
        raise ValueError(f"hue must be one of {sorted(_COMPARE_HUE_FIELDS)}, got {hue!r}")
    recs = records(results)
    if not recs:
        return None
    frame = _compare_frame(
        recs,
        settings,
        hue=hue,
        include_brem=include_brem,
        include_cxr=include_cxr,
        include_characteristic=include_characteristic,
        include_channeling=include_channeling,
        include_coherent=include_coherent,
        sum_components=sum_components,
        band=band,
        max_points=max_points,
    )
    return _trace_series(
        frame,
        hue=hue,
        components=("total",)
        + (("brem",) if include_brem and not sum_components else ())
        + (("line",) if include_cxr and not sum_components else ())
        + (("coherent",) if include_coherent else ()),
        width=width,
        height=height,
        title=_case_title(recs[0]["case"], "comparison", latex=False),
        x_type=x_type,
        y_type=y_type,
        x_domain=_narrow_line_domain(recs, band, x_domain),
    )


def multi_case_spectrum_chart(
    cases,
    settings,
    *,
    include_brem=True,
    include_cxr=False,
    include_characteristic=True,
    include_channeling=True,
    include_coherent=False,
    sum_components=False,
    x_domain=None,
    x_type="linear",
    y_type="linear",
    band="narrow",
    max_points=5000,
    width=720,
    height=360,
):
    """Plot an explicitly selected case basket without collapsing equal parameters."""
    _validate_band(band)
    if not cases:
        return None
    # Labels can repeat for independently selected records: distinguish them
    # before preparing the shared frames rather than letting pandas merge them.
    count: dict[str, int] = {}
    distinct = []
    for record, label in cases:
        label = str(label)
        count[label] = count.get(label, 0) + 1
        distinct.append((record, label if count[label] == 1 else f"{label} (#{count[label]})"))
    frame = _multi_case_frame(
        distinct,
        settings,
        include_brem=include_brem,
        include_cxr=include_cxr,
        include_characteristic=include_characteristic,
        include_channeling=include_channeling,
        include_coherent=include_coherent,
        sum_components=sum_components,
        band=band,
        max_points=max_points,
    )
    return _trace_series(
        frame,
        hue="label",
        components=("total",)
        + (("brem",) if include_brem and not sum_components else ())
        + (("line",) if include_cxr and not sum_components else ())
        + (("coherent",) if include_coherent else ()),
        width=width,
        height=height,
        title="Case comparison",
        x_type=x_type,
        y_type=y_type,
        x_domain=_narrow_line_domain((r for r, _ in cases), band, x_domain),
    )


def material_comparison_chart(
    points,
    dropped,
    select="quality_line",
    beam_energy_keV=None,
    min_cxr_quality: float | None = 0.5,
    width=760,
    height=460,
):
    """Render the existing precomputed material/line-selection tuples with Plotly."""
    if not points:
        return None
    labels = [str(p[0]) for p in points]
    x = [p[1] / 1e3 for p in points]
    y = [p[2] if p[2] > 0 else None for p in points]
    quality = [p[3] for p in points]
    hover = [
        f"{label}<br>Beam: {case['E0_keV']:g} keV"
        f"<br>Polar tilt: {case['tilt_deg']:g}°"
        f"<br>Azimuth: {case['tilt_azim_deg']:g}°"
        for label, _, _, _, case in points
    ]
    fig = go.Figure()
    fig.add_trace(
        go.Scatter(
            x=x,
            y=y,
            mode="markers+text",
            text=labels,
            textposition="top center",
            customdata=hover,
            marker=dict(
                size=11,
                color=quality,
                colorscale="Viridis",
                cmin=0,
                cmax=1,
                colorbar=dict(title="Line quality"),
                line=dict(color="black", width=0.7),
            ),
            hovertemplate="%{customdata}<br>Line: %{x:.5g} keV<br>Flux: %{y:.5g} Phs/s<extra></extra>",
        )
    )
    scope = (
        "all beam energies" if beam_energy_keV is None else f"{beam_energy_keV:g} keV beam energy"
    )
    quality_scope = "" if min_cxr_quality is None else f", line quality ≥ {min_cxr_quality:g}"
    fig.update_layout(
        title=f"Cross-material comparison — {select.replace('_', ' ')} ({scope}{quality_scope})",
        width=width,
        height=height,
        showlegend=False,
        xaxis_title="Dominant coherent line energy (keV)",
        yaxis=dict(title="Integrated line flux at best geometry (Phs/s)", type="log"),
    )
    if dropped:
        print(f"Dropped materials: {_comparison_drop_message(dropped)}")
    return fig

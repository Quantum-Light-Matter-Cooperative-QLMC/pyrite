"""Generate documentation schematics; run with ``uv run python scripts/docs_figures.py``.

Only the Python standard library is needed. These SVGs contain no simulation data.
"""

from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "_static" / "figures"


def text(x: int, y: int, label: str, size: int = 20, anchor: str = "start") -> str:
    return f'<text x="{x}" y="{y}" font-size="{size}" text-anchor="{anchor}">{escape(label)}</text>'


def line(x1: int, y1: int, x2: int, y2: int, dashed: bool = False) -> str:
    dash = ' stroke-dasharray="7 5"' if dashed else ""
    return (
        f'<path d="M{x1},{y1} L{x2},{y2}" fill="none" stroke="#243b53" '
        f'stroke-width="2.5" marker-end="url(#arrow)"{dash}/>'
    )


def svg(width: int, height: int, title: str, description: str, body: str) -> str:
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}"
 role="img" aria-labelledby="title desc">
<title id="title">{escape(title)}</title>
<desc id="desc">{escape(description)}</desc>
<!-- Generated by scripts/docs_figures.py; schematic, not measured or simulated. -->
<defs><marker id="arrow" markerWidth="9" markerHeight="9" refX="8" refY="4"
 orient="auto" markerUnits="userSpaceOnUse"><path d="M0,0 L8,4 L0,8 Z" fill="#243b53"/></marker></defs>
<rect width="100%" height="100%" fill="#fff"/>
<g font-family="DejaVu Sans, sans-serif" fill="#172b4d">
{body}
</g>
</svg>
"""


def pipeline() -> str:
    parts = [text(360, 38, "From inputs to an observation", 25, "middle")]
    stages = [
        (
            "1  Describe a case",
            "Beam · target · observation geometry",
            "Physics choices · numerical settings",
        ),
        (
            "2  Transport electrons",
            "Entrance phase space → material flights",
            "Scattering · energy loss · boundary exits",
        ),
        (
            "3  Score source spectra",
            "PXR/CBS · continuum · characteristic",
            "Keep components and photon grids explicit",
        ),
        (
            "4  Retain results",
            "API: in-memory Result",
            "Profile run: resumable component checkpoints",
        ),
        (
            "5  Apply an observation model",
            "Acceptance · filters · response · acquisition",
            "Inspect spectra, counts or pixel observations",
        ),
    ]
    for i, (title, first, second) in enumerate(stages):
        y = 65 + 150 * i
        parts.extend(
            [
                f'<rect x="35" y="{y}" width="650" height="118" rx="12" '
                'fill="#edf4fa" stroke="#486581" stroke-width="2"/>',
                text(58, y + 30, title, 22),
                text(58, y + 65, first, 20),
                text(58, y + 94, second, 19),
            ]
        )
        if i < len(stages) - 1:
            parts.append(line(360, y + 122, 360, y + 144))
    parts.append(text(360, 824, "Schematic workflow; no measured or simulated data", 18, "middle"))
    return svg(
        720,
        850,
        "PyRITE simulation workflow",
        "Five stages: describe a case, transport electrons, score source spectra, retain results, and apply an observation model. Observation effects are downstream of source scoring.",
        "\n".join(parts),
    )



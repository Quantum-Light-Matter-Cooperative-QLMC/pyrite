        text(240, 78, "Lab frame: tilt azimuth = 0", 22, "middle"),
        text(700, 78, "Sample frame: normal incidence", 22, "middle"),
        '<path d="M520,95 V485" stroke="#9fb3c8" stroke-dasharray="5 5"/>',
        # Tilted slab in the lab x-z section; dimensions are arbitrary.
        '<polygon points="100,315 380,153 438,254 158,416" fill="#edf4fa" stroke="#486581" stroke-width="2"/>',
        line(240, 100, 240, 234),
        text(118, 125, "Incident beam", 18),
        line(240, 234, 477, 234),
        text(448, 221, "+x lab", 18),
        line(240, 234, 240, 465, True),
        text(252, 461, "+z lab", 18),
        line(240, 234, 325, 381),
        text(322, 402, "Sample normal", 18),
        line(240, 234, 380, 94),
        text(395, 110, "Detector", 18),
        text(395, 132, "direction", 18),
        '<path d="M240,300 A66,66 0 0,0 273,291" fill="none" stroke="#486581" stroke-width="2"/>',
        text(259, 323, "Tilt", 18),
        '<path d="M240,278 A44,44 0 0,0 271,203" fill="none" stroke="#486581" stroke-width="2"/>',

        text(240, 493, "Origin: beam meets entrance face", 17, "middle"),
        # A separate normal-incidence view makes sample depth unambiguous.
        '<rect x="560" y="210" width="285" height="185" fill="#edf4fa" stroke="#486581" stroke-width="2"/>',
        line(655, 110, 655, 208),
        text(672, 145, "Beam", 18),

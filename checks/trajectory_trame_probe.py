"""Optional reactive-server smoke or connected-browser probe.

Use the 200-keV shell-soft-hard fixture generated by trajectory_viewer_benchmark.

Usage: uv run --with pyvista --with trame --with trame-vtk --with trame-vuetify \
    python checks/trajectory_trame_probe.py tracks.vtp image.png report.json

Add --serve --port 8765 to inspect the remote view in a browser. Save report
records server callbacks and a screenshot; it does not measure browser latency.
"""

import argparse
import asyncio
import hashlib
import importlib.metadata
import json
import resource
from pathlib import Path
from time import perf_counter

import pyvista as pv
from trame.app import get_server
from trame.ui.vuetify3 import SinglePageLayout
from trame.widgets import vtk, vuetify3

pv.OFF_SCREEN = True
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("tracks", type=Path)
parser.add_argument("image", type=Path)
parser.add_argument("report", type=Path)
parser.add_argument("--serve", action="store_true")
parser.add_argument("--port", type=int, default=0)
args = parser.parse_args()
mesh = pv.read(args.tracks)
plotter = pv.Plotter(window_size=(800, 600))
actor = plotter.add_mesh(mesh, name="tracks", scalars="E_start_keV", cmap="turbo", clim=(0, 200))
plotter.camera_position = "iso"
server = get_server("trajectory-probe", client_type="vue3")
state, ctrl = server.state, server.controller
transitions = []
client_connections = []
initial_camera = tuple(plotter.camera_position)


def connected(**_):
    client_connections.append(perf_counter())


def preset(energy, secondaries):
    with state:
        state.energy_min = energy
        state.secondaries = secondaries


def save_report():
    plotter.screenshot(args.image)
    args.report.write_text(
        json.dumps(
            dict(
                mode="VtkRemoteView",
                client_connected=bool(client_connections),
                client_connections=len(client_connections),
                input_sha256=hashlib.sha256(args.tracks.read_bytes()).hexdigest(),
                input_bytes=args.tracks.stat().st_size,
                segments=mesh.n_cells,
                transitions=transitions,
                initial_camera=initial_camera,
                final_camera=tuple(plotter.camera_position),
                process_peak_rss_mib=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024,
                versions={
                    name: importlib.metadata.version(name)
                    for name in ("pyvista", "vtk", "trame", "trame-vtk", "trame-vuetify")
                },
                notes="Server callback costs exclude browser delivery/display; RSS excludes browser.",
            ),
            indent=2,
        ),
        encoding="utf-8",
    )


ctrl.on_client_connected.add(connected)
with SinglePageLayout(server) as layout:
    layout.title.set_text("Trajectory rendering probe")
    with layout.toolbar:
        vuetify3.VSlider(
            v_model=("energy_min", 0), min=0, max=200, step=1, label="Minimum energy (keV)"
        )
        vuetify3.VSwitch(v_model=("secondaries", True), label="Include secondaries")
        if args.serve:
            vuetify3.VBtn("Energy 10", click=lambda: preset(10, True))
            vuetify3.VBtn("Primaries", click=lambda: preset(10, False))
            vuetify3.VBtn("Restore", click=lambda: preset(0, True))
            vuetify3.VBtn("Save report", click=save_report)
    with layout.footer:
        vuetify3.VLabel("Selected cells: {{ selected_cells }}")
    with layout.content:
        with vuetify3.VContainer(fluid=True, classes="pa-0 fill-height"):
            view = vtk.VtkRemoteView(plotter.render_window)
            ctrl.view_update = view.update
            ctrl.reset_camera = view.reset_camera


@state.change("energy_min", "secondaries")
def update(energy_min=0, secondaries=True, **_):
    global actor
    tick = perf_counter()
    keep = mesh.cell_data["E_start_keV"] >= energy_min
    if not secondaries:
        keep &= mesh.cell_data["generation"] == 0
    selected = mesh.extract_cells(keep).extract_surface(algorithm="dataset_surface")
    if selected.n_cells:
        actor = plotter.add_mesh(
            selected, name="tracks", scalars="E_start_keV", cmap="turbo", clim=(0, 200), render=False
        )
    else:
        plotter.remove_actor("tracks", render=False)
        actor = None
    state.selected_cells = selected.n_cells
    plotter.render()
    ctrl.view_update()
    transitions.append(
        dict(
            energy_min=energy_min,
            secondaries=secondaries,
            cells=state.selected_cells,
            server_callback_s=perf_counter() - tick,
        )
    )


failures = []


async def smoke(**_):
    try:
        results = []
        for energy, secondaries in ((0, True), (10, True), (10, False), (0, True)):
            tick = perf_counter()
            with state:
                state.energy_min = energy
                state.secondaries = secondaries
            await asyncio.sleep(0.02)
            assert actor.mapper.dataset.n_cells == state.selected_cells
            # State callbacks update the mapper via the same path as UI controls.
            results.append(
                dict(
                    energy_min=energy,
                    secondaries=secondaries,
                    cells=state.selected_cells,
                    state_to_update_s=perf_counter() - tick,
                )
            )
        assert results[0]["cells"] == results[-1]["cells"] == mesh.n_cells
        assert 0 < results[1]["cells"] < mesh.n_cells
        assert 0 < results[2]["cells"] < results[1]["cells"]
        with state:
            state.energy_min = float(mesh.cell_data["E_start_keV"].max()) + 1
        await asyncio.sleep(0.02)
        assert state.selected_cells == 0 and actor is None
        with state:
            state.energy_min = 0
        await asyncio.sleep(0.02)
        assert state.selected_cells == mesh.n_cells and actor is not None
        save_report()
        print(json.dumps(results), flush=True)
    except Exception as error:
        failures.append(error)
    finally:
        await server.stop()
        plotter.close()


if not args.serve:
    ctrl.on_server_ready.add(lambda **kw: asyncio.create_task(smoke(**kw)))
server.start(
    host="127.0.0.1", port=args.port, open_browser=False, show_connection_info=args.serve
)

if failures:
    raise RuntimeError("reactive server smoke failed") from failures[0]
